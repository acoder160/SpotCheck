// Embeds the map's spot icons as data URIs in constants/spotIcons.ts.
// The map is a WebView loaded from an HTML string: in release builds an image asset's uri is an
// Android resource name (not a URL), so <img src> can't load it. Data URIs work everywhere.
// Run after changing an icon: npm run icons
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const ICONS = {
  STREET: 'icon_street.png',
  PARK: 'icon_park.png', // SKATEPARK uses it too (see components/spotcheck.tsx)
  RAMPS: 'icon_ramps.png',
  RAIL: 'icon_rail.png',
  LEDGE: 'icon_ledge.png',
};

const lines = Object.entries(ICONS).map(([type, file]) => {
  const data = fs.readFileSync(path.join(root, 'assets', 'images', file)).toString('base64');
  return `  ${type}: 'data:image/png;base64,${data}',`;
});

const out = `// Generated by scripts/gen-spot-icons.js from assets/images/icon_*.png. Do not edit: run npm run icons.
export const SPOT_ICON_URIS: Record<string, string> = {
${lines.join('\n')}
};
`;

fs.writeFileSync(path.join(root, 'constants', 'spotIcons.ts'), out);
console.log('constants/spotIcons.ts written');
